"""Rendering `docs/verification/evaluation.md` from measurements — and refusing to over-claim.

Every file under `docs/verification/` is generated by a script that spends money, and this one
is T10's. The rules it enforces on its own output are the same ones `security/report.py`
enforces on its:

- **A partial run says so, above the numbers.** `scripts/evaluate.py --stage` can run any
subset,
  and a table rendered from three of five stages must not read as a whole run — the
  `--gate-only` precedent, where the artifact's only signal had been `0/0 planted payload(s)
  resisted`.
- **Every bucket mean is rendered with its spread and its n**, never alone. With 7 questions per
  bucket a bare mean invites a comparison the sample cannot support.
- **A difference inside the spread is printed as "within spread", not as a delta with a sign.**
- **An absence is printed as a word, never as a number.** `—` for a metric that was not defined,
  with the count of absences beside the mean, because "we cannot say" and "it scored zero" are
  different claims.
- **The fenced metric is labelled where it is printed.** Response relevancy is
non-reproducible by
  construction (`judge.EXCLUDED_FROM_HYPOTHESES`), so its column carries the note in the table
  rather than in a paragraph underneath that a reader of the table does not see.
- **The tool-augmented relevancy cell is not a number at all.** See `_relevancy_cell`.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any

from finbrief.evaluation.arms import Arm
from finbrief.evaluation.cache import CacheStats
from finbrief.evaluation.judge import (
    ANSWER_RELEVANCY,
    EXCLUDED_FROM_HYPOTHESES,
    METRICS,
)
from finbrief.evaluation.loader import Bucket, GoldenSet
from finbrief.evaluation.metrics import Comparison, Summary, Verdict, summarise
from finbrief.evaluation.pipeline import Cell

#: The free metrics, and the column heading each gets.
FREE_METRICS: tuple[tuple[str, str], ...] = (
    ("precision_at_k", "precision@k"),
    ("chunk_recall", "chunk recall"),
    ("section_recall", "section recall"),
    ("filer_precision", "filer precision"),
)

ABSENT = "—"


@dataclass(frozen=True, slots=True)
class Provenance:
    """What produced these numbers. Quoted above them, so no figure is unattributable."""

    generated_at: str
    judge_model: str
    chat_model: str
    embedding_model: str
    planner_model: str
    ragas_version: str
    k: int
    collection_ingest_run: str
    collection_fingerprint: str
    golden_set_rows: int
    #: Which stages this run actually executed. A run missing one is a partial run.
    stages: tuple[str, ...]
    cache: Mapping[str, CacheStats] = field(default_factory=dict)


#: Every stage a complete run executes. A rendered artifact naming fewer is banner-flagged.
ALL_STAGES: tuple[str, ...] = ("resolve", "retrieve", "answer", "judge", "report")


def is_partial(provenance: Provenance) -> bool:
    """Whether this run skipped a stage a complete one would have run."""
    return set(provenance.stages) != set(ALL_STAGES)


def fmt(value: float | None, *, places: int = 3) -> str:
    """A number, or the absence marker — never a zero standing in for one."""
    return ABSENT if value is None else f"{value:.{places}f}"


def cell(summary: Summary, *, places: int = 3) -> str:
    """`0.714 [0.400–1.000] n=7` — a mean that cannot be read without its spread.

    An absence count is appended when there is one, so a mean over 4 of 7 rows says so in the
    cell rather than in a footnote.
    """
    if summary.mean is None:
        return f"{ABSENT} (n=0 of {summary.total})"
    body = (
        f"{summary.mean:.{places}f} "
        f"[{fmt(summary.minimum, places=places)}–{fmt(summary.maximum, places=places)}] "
        f"n={summary.n}"
    )
    return body if not summary.absent else f"{body}, {summary.absent} absent"


def verdict_cell(comparison: Comparison) -> str:
    """A comparison as text, printing no signed delta where the sample cannot support one."""
    if comparison.verdict is Verdict.UNDETERMINED:
        return "undetermined (a side has no number)"
    if comparison.verdict is Verdict.WITHIN_SPREAD:
        return f"within spread (Δ {comparison.delta:+.3f}, spread {fmt(comparison.basis)})"
    return (
        f"{comparison.verdict.value} "
        f"(Δ {comparison.delta:+.3f} > spread {fmt(comparison.basis)})"
    )


def _by_bucket(cells: Sequence[Cell], arm_name: str) -> Mapping[Bucket, tuple[Cell, ...]]:
    return {
        bucket: tuple(c for c in cells if c.arm == arm_name and c.bucket is bucket)
        for bucket in Bucket
    }


def free_metric_table(cells: Sequence[Cell], arms: Sequence[Arm]) -> str:
    """The per-bucket A/B on the deterministic metrics — the table that carries the result."""
    lines = [
        "| bucket | arm | " + " | ".join(label for _, label in FREE_METRICS) + " |",
        "|---|---|" + "---|" * len(FREE_METRICS),
    ]
    for bucket in Bucket:
        for arm in arms:
            rows = _by_bucket(cells, arm.name)[bucket]
            if not rows:
                continue
            columns = []
            for attribute, _ in FREE_METRICS:
                # Recall excludes whole trivial rows; precision does not — a small target
                # section does not make a precision measurement trivial (`metrics.summarise`).
                exclude = attribute in {"chunk_recall", "section_recall"}
                scores = [row.score for row in rows]
                columns.append(cell(summarise(scores, attribute, exclude_trivial=exclude)))
            lines.append(f"| {bucket.value} | {arm.label} | " + " | ".join(columns) + " |")
    return "\n".join(lines)


def _relevancy_cell(bucket: Bucket, rows: Sequence[Cell]) -> str:
    """Response relevancy for one bucket — or, on `tool-augmented`, why it is not comparable.

    **The one cell in this artifact that is deliberately not a number** (#11, addition 3). A
    `tool-augmented` question asks partly for a live figure, the measured chain calls no
    tools, and a chain answer that correctly says "the retrieved filings do not give a current
    share price" is scored by ragas as *noncommittal* — which is a floor of ≈0 for being
    right. Printing that beside a semantic bucket's 0.9 would invite exactly the comparison it
    cannot support, so the count of noncommittal answers is printed instead of a mean.
    """
    if bucket is not Bucket.TOOL_AUGMENTED:
        return cell(_summarise_judged(rows, ANSWER_RELEVANCY))
    noncommittal = sum(
        1 for row in rows if (row.judged.get(ANSWER_RELEVANCY) or 0.0) < NONCOMMITTAL_FLOOR
    )
    return f"not comparable — {noncommittal}/{len(rows)} noncommittal"


#: Below this, ragas' `noncommittal` flag has almost certainly fired: the metric multiplies
#: the cosine similarity by `not noncommittal`, so a flagged answer scores exactly 0.0. A
#: floor rather than an equality because a genuinely irrelevant answer can score near zero
#: too, and the cell says "noncommittal" about both — which is why it is a count and not a
#: mean.
NONCOMMITTAL_FLOOR = 0.05


def ragas_table(cells: Sequence[Cell], arms: Sequence[Arm]) -> str:
    """The four RAGAs metrics per bucket per arm, with the fenced column labelled."""
    headings = []
    for metric in METRICS:
        label = metric.replace("_", " ")
        headings.append(f"{label} ⚠" if metric in EXCLUDED_FROM_HYPOTHESES else label)
    lines = [
        "| bucket | arm | " + " | ".join(headings) + " |",
        "|---|---|" + "---|" * len(METRICS),
    ]
    for bucket in Bucket:
        for arm in arms:
            rows = _by_bucket(cells, arm.name)[bucket]
            if not rows or not arm.judged:
                continue
            columns = []
            for metric in METRICS:
                if metric == ANSWER_RELEVANCY:
                    columns.append(_relevancy_cell(bucket, rows))
                else:
                    columns.append(cell(_summarise_judged(rows, metric)))
            lines.append(f"| {bucket.value} | {arm.label} | " + " | ".join(columns) + " |")
    lines.append("")
    lines.append(
        "⚠ **response relevancy is excluded from every pre-registered decision.** ragas forces "
        "temperature 0.3 whenever it asks for n > 1 completions (`ragas.llms.base."
        "get_temperature`) and `ResponseRelevancy` asks for n=3, so this column moves between "
        "runs on any judge at any temperature this code names. It is reported with its "
        "spread and "
        "read as nothing else. ADR-0005's falsification clause and its §4 re-examination "
        "trigger "
        "both rest on context precision and context recall, which are single-call metrics."
    )
    return "\n".join(lines)


def _summarise_judged(rows: Sequence[Cell], metric: str) -> Summary:
    return Summary.of(row.judged.get(metric) for row in rows)


def render_report(
    *,
    provenance: Provenance,
    golden: GoldenSet,
    cells: Sequence[Cell],
    arms: Sequence[Arm],
    ablations: Sequence[Arm] = (),
    sections: Sequence[tuple[str, str]] = (),
) -> str:
    """The whole artifact. `sections` are appended verbatim, heading and body, in order."""
    parts = [
        "# Evaluation — RAGAs, per-bucket A/B, tool-calling (T10, #11)",
        "",
        "<!-- GENERATED FILE. Rewritten by `uv run python scripts/evaluate.py`. Do not edit: "
        "every number here is a measurement of the run named below. -->",
        "",
    ]
    if is_partial(provenance):
        missing = [stage for stage in ALL_STAGES if stage not in provenance.stages]
        parts += [
            f"> ## ⚠ PARTIAL RUN — stages not executed: {', '.join(missing)}",
            ">",
            "> This artifact was rendered from a subset of the pipeline, so it is **not** a "
            "whole "
            "run and must not be committed as one. Numbers below cover only the stages "
            "listed in "
            "the provenance table; anything a skipped stage would have produced is absent "
            "rather "
            "than zero.",
            "",
        ]
    parts += [_provenance_table(provenance, golden), ""]
    parts += [
        "## Per-bucket A/B — the deterministic retrieval metrics",
        "",
        "No judge, no spend: every figure below is computed from `Retrieval`'s own return "
        "value "
        "against the golden set's chunk ids, so a reviewer can re-derive it. Recall columns "
        "exclude whole `recall_trivial` rows (reported separately) and count only sections a "
        f"`k={provenance.k}` retrieval could miss.",
        "",
        free_metric_table(cells, arms),
        "",
    ]
    parts += [
        "## RAGAs — all four metrics, per bucket",
        "",
        ragas_table(cells, arms),
        "",
    ]
    if ablations:
        parts += [
            "## Ablations — the planner off (ADR-0004 §7, ADR-0005 §2)",
            "",
            "Translation on, `max_sub_queries=0`: the deterministic ticker form is still "
            "added and "
            "no model is asked anything, which is the channel ADR-0005 §2 pre-registered for "
            "refuting its own revised hypothesis. Retrieval metrics only — these cells exist "
            "to "
            "attribute a retrieval result, and faithfulness over an answer is not evidence "
            "about "
            "which candidate list found a chunk.",
            "",
            free_metric_table(cells, ablations),
            "",
        ]
    for heading, body in sections:
        parts += [heading, "", body, ""]
    return "\n".join(parts).rstrip() + "\n"


def _provenance_table(provenance: Provenance, golden: GoldenSet) -> str:
    cache_lines = ", ".join(
        f"{kind} {stats.hits} replayed / {stats.misses} paid"
        + (f" / {stats.malformed} unreadable" if stats.malformed else "")
        for kind, stats in sorted(provenance.cache.items())
    )
    rows: list[tuple[str, str]] = [
        ("generated", provenance.generated_at),
        ("stages run", ", ".join(provenance.stages)),
        ("judge model", f"`{provenance.judge_model}` (ragas {provenance.ragas_version})"),
        ("answering model", f"`{provenance.chat_model}`"),
        ("planner model", f"`{provenance.planner_model}`"),
        ("embedding model", f"`{provenance.embedding_model}`"),
        ("k", str(provenance.k)),
        ("golden set", f"{provenance.golden_set_rows} rows, verified against EDGAR"),
        ("collection", provenance.collection_ingest_run),
        ("collection fingerprint", f"`{provenance.collection_fingerprint[:16]}…`"),
        ("cache", cache_lines or "not used"),
    ]
    del golden
    return "\n".join(
        ["| | |", "|---|---|"] + [f"| {label} | {value} |" for label, value in rows]
    )


def hypothesis_section(entries: Sequence[Mapping[str, Any]]) -> str:
    """Each pre-registered prediction, then its measurement, then confirmed or refuted.

    Prediction **first**, in its own column, so the artifact cannot be read as having fitted
    the prediction to the result — which is the whole reason ADR-0005 pre-registers anything.
    A refuted prediction is a result: ADR-0004 §6 is the precedent, where a pre-registered
    hypothesis failed and the failure improved the ADR.
    """
    lines = [
        "| # | prediction (pre-registered) | measurement | verdict |",
        "|---|---|---|---|",
    ]
    for index, entry in enumerate(entries, start=1):
        lines.append(
            f"| {index} | {entry['prediction']} | {entry['measurement']} "
            f"| **{entry['verdict']}** |"
        )
    return "\n".join(lines)
