"""Rendering `docs/verification/evaluation.md` from measurements — and refusing to over-claim.

Every file under `docs/verification/` is generated by a script that spends money, and this one
is T10's. The rules it enforces on its own output are the same ones `security/report.py`
enforces on its:

- **A partial run says so, above the numbers.** `scripts/evaluate.py --stage` can run any
subset,
  and a table rendered from three of five stages must not read as a whole run — the
  `--gate-only` precedent, where the artifact's only signal had been `0/0 planted payload(s)
  resisted`.
- **Every bucket mean is rendered with its spread and its n**, never alone. With 7 questions per
  bucket a bare mean invites a comparison the sample cannot support.
- **A difference the paired test does not resolve is printed as "not detected", not as a delta
  with a sign — and one it could never have resolved is printed as "undetectable".** The two are
  separate columns' worth of claim: see `metrics`' module docstring for the defect that made
  them one.
- **An absence is printed as a word, never as a number.** `—` for a metric that was not defined,
  with the count of absences beside the mean, because "we cannot say" and "it scored zero" are
  different claims.
- **The fenced metric is labelled where it is printed.** Response relevancy is
non-reproducible by
  construction (`judge.EXCLUDED_FROM_HYPOTHESES`), so its column carries the note in the table
  rather than in a paragraph underneath that a reader of the table does not see.
- **The tool-augmented relevancy cell is not a number at all.** See `_relevancy_cell`.
"""

