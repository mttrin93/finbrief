"""Rendering `docs/verification/evaluation.md` from measurements — and refusing to over-claim.

Every file under `docs/verification/` is generated by a script that spends money, and this one
is T10's. The rules it enforces on its own output are the same ones `security/report.py`
enforces on its:

- **A partial run says so, above the numbers.** `scripts/evaluate.py --stage` can run any
subset,
  and a table rendered from three of five stages must not read as a whole run — the
  `--gate-only` precedent, where the artifact's only signal had been `0/0 planted payload(s)
  resisted`.
- **Every bucket mean is rendered with its spread and its n**, never alone. With 7 questions per
  bucket a bare mean invites a comparison the sample cannot support.
- **A difference inside the spread is printed as "within spread", not as a delta with a sign.**
- **An absence is printed as a word, never as a number.** `—` for a metric that was not defined,
  with the count of absences beside the mean, because "we cannot say" and "it scored zero" are
  different claims.
- **The fenced metric is labelled where it is printed.** Response relevancy is
non-reproducible by
  construction (`judge.EXCLUDED_FROM_HYPOTHESES`), so its column carries the note in the table
  rather than in a paragraph underneath that a reader of the table does not see.
- **The tool-augmented relevancy cell is not a number at all.** See `_relevancy_cell`.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any

from finbrief.evaluation.arms import Arm
from finbrief.evaluation.cache import CacheStats
from finbrief.evaluation.judge import (
    ANSWER_RELEVANCY,
    EXCLUDED_FROM_HYPOTHESES,
    METRICS,
)
from finbrief.evaluation.loader import Bucket, GoldenSet
from finbrief.evaluation.metrics import Comparison, Summary, Verdict, summarise
from finbrief.evaluation.pipeline import Cell

#: The free metrics, and the column heading each gets.
FREE_METRICS: tuple[tuple[str, str], ...] = (
    ("precision_at_k", "precision@k"),
    ("chunk_recall", "chunk recall"),
    ("section_recall", "section recall"),
    ("filer_precision", "filer precision"),
)

ABSENT = "—"


@dataclass(frozen=True, slots=True)
class Provenance:
    """What produced these numbers. Quoted above them, so no figure is unattributable."""

    generated_at: str
    judge_model: str
    chat_model: str
    embedding_model: str
    planner_model: str
    ragas_version: str
    k: int
    collection_ingest_run: str
    collection_fingerprint: str
    golden_set_rows: int
    #: Which stages this run actually executed. A run missing one is a partial run.
    stages: tuple[str, ...]
    cache: Mapping[str, CacheStats] = field(default_factory=dict)


#: Every stage a complete run executes. A rendered artifact naming fewer is banner-flagged.
ALL_STAGES: tuple[str, ...] = ("resolve", "retrieve", "answer", "judge", "report")


def is_partial(provenance: Provenance) -> bool:
    """Whether this run skipped a stage a complete one would have run."""
    return set(provenance.stages) != set(ALL_STAGES)


def fmt(value: float | None, *, places: int = 3) -> str:
    """A number, or the absence marker — never a zero standing in for one."""
    return ABSENT if value is None else f"{value:.{places}f}"


def cell(summary: Summary, *, places: int = 3) -> str:
    """`0.714 [0.400–1.000] n=7` — a mean that cannot be read without its spread.

    An absence count is appended when there is one, so a mean over 4 of 7 rows says so in the
    cell rather than in a footnote.
    """
    if summary.mean is None:
        return f"{ABSENT} (n=0 of {summary.total})"
    body = (
        f"{summary.mean:.{places}f} "
        f"[{fmt(summary.minimum, places=places)}–{fmt(summary.maximum, places=places)}] "
        f"n={summary.n}"
    )
    return body if not summary.absent else f"{body}, {summary.absent} absent"


def verdict_cell(comparison: Comparison) -> str:
    """A comparison as text, printing no signed delta where the sample cannot support one."""
    if comparison.verdict is Verdict.UNDETERMINED:
        return "undetermined (a side has no number)"
    if comparison.verdict is Verdict.WITHIN_SPREAD:
        return f"within spread (Δ {comparison.delta:+.3f}, spread {fmt(comparison.basis)})"
    return (
        f"{comparison.verdict.value} "
        f"(Δ {comparison.delta:+.3f} > spread {fmt(comparison.basis)})"
    )


def _by_bucket(cells: Sequence[Cell], arm_name: str) -> Mapping[Bucket, tuple[Cell, ...]]:
    return {
        bucket: tuple(c for c in cells if c.arm == arm_name and c.bucket is bucket)
        for bucket in Bucket
    }


def free_metric_table(cells: Sequence[Cell], arms: Sequence[Arm]) -> str:
    """The per-bucket A/B on the deterministic metrics — the table that carries the result."""
    lines = [
        "| bucket | arm | " + " | ".join(label for _, label in FREE_METRICS) + " |",
        "|---|---|" + "---|" * len(FREE_METRICS),
    ]
    for bucket in Bucket:
        for arm in arms:
            rows = _by_bucket(cells, arm.name)[bucket]
            if not rows:
                continue
            columns = []
            for attribute, _ in FREE_METRICS:
                # Recall excludes whole trivial rows; precision does not — a small target
                # section does not make a precision measurement trivial (`metrics.summarise`).
                exclude = attribute in {"chunk_recall", "section_recall"}
                scores = [row.score for row in rows]
                columns.append(cell(summarise(scores, attribute, exclude_trivial=exclude)))
            lines.append(f"| {bucket.value} | {arm.label} | " + " | ".join(columns) + " |")
    return "\n".join(lines)


def _relevancy_cell(bucket: Bucket, rows: Sequence[Cell]) -> str:
    """Response relevancy for one bucket — or, on `tool-augmented`, why it is not comparable.

    **The one cell in this artifact that is deliberately not a number** (#11, addition 3). A
    `tool-augmented` question asks partly for a live figure, the measured chain calls no
    tools, and a chain answer that correctly says "the retrieved filings do not give a current
    share price" is scored by ragas as *noncommittal* — which is a floor of ≈0 for being
    right. Printing that beside a semantic bucket's 0.9 would invite exactly the comparison it
    cannot support, so the count of noncommittal answers is printed instead of a mean.
    """
    if bucket is not Bucket.TOOL_AUGMENTED:
        return cell(_summarise_judged(rows, ANSWER_RELEVANCY))
    noncommittal = sum(
        1 for row in rows if (row.judged.get(ANSWER_RELEVANCY) or 0.0) < NONCOMMITTAL_FLOOR
    )
    return f"not comparable — {noncommittal}/{len(rows)} noncommittal"


#: Below this, ragas' `noncommittal` flag has almost certainly fired: the metric multiplies
#: the cosine similarity by `not noncommittal`, so a flagged answer scores exactly 0.0. A
#: floor rather than an equality because a genuinely irrelevant answer can score near zero
#: too, and the cell says "noncommittal" about both — which is why it is a count and not a
#: mean.
NONCOMMITTAL_FLOOR = 0.05


def ragas_table(cells: Sequence[Cell], arms: Sequence[Arm]) -> str:
    """The four RAGAs metrics per bucket per arm, with the fenced column labelled."""
    headings = []
    for metric in METRICS:
        label = metric.replace("_", " ")
        headings.append(f"{label} ⚠" if metric in EXCLUDED_FROM_HYPOTHESES else label)
    lines = [
        "| bucket | arm | " + " | ".join(headings) + " |",
        "|---|---|" + "---|" * len(METRICS),
    ]
    for bucket in Bucket:
        for arm in arms:
            rows = _by_bucket(cells, arm.name)[bucket]
            if not rows or not arm.judged:
                continue
            columns = []
            for metric in METRICS:
                if metric == ANSWER_RELEVANCY:
                    columns.append(_relevancy_cell(bucket, rows))
                else:
                    columns.append(cell(_summarise_judged(rows, metric)))
            lines.append(f"| {bucket.value} | {arm.label} | " + " | ".join(columns) + " |")
    lines.append("")
    lines.append(
        "⚠ **response relevancy is excluded from every pre-registered decision.** ragas forces "
        "temperature 0.3 whenever it asks for n > 1 completions (`ragas.llms.base."
        "get_temperature`) and `ResponseRelevancy` asks for n=3, so this column moves between "
        "runs on any judge at any temperature this code names. It is reported with its "
        "spread and "
        "read as nothing else. ADR-0005's falsification clause and its §4 re-examination "
        "trigger "
        "both rest on context precision and context recall, which are single-call metrics."
    )
    return "\n".join(lines)


def _summarise_judged(rows: Sequence[Cell], metric: str) -> Summary:
    return Summary.of(row.judged.get(metric) for row in rows)


def render_report(
    *,
    provenance: Provenance,
    golden: GoldenSet,
    cells: Sequence[Cell],
    arms: Sequence[Arm],
    ablations: Sequence[Arm] = (),
    sections: Sequence[tuple[str, str]] = (),
) -> str:
    """The whole artifact. `sections` are appended verbatim, heading and body, in order."""
    parts = [
        "# Evaluation — RAGAs, per-bucket A/B, tool-calling (T10, #11)",
        "",
        "<!-- GENERATED FILE. Rewritten by `uv run python scripts/evaluate.py`. Do not edit: "
        "every number here is a measurement of the run named below. -->",
        "",
    ]
    if is_partial(provenance):
        missing = [stage for stage in ALL_STAGES if stage not in provenance.stages]
        parts += [
            f"> ## ⚠ PARTIAL RUN — stages not executed: {', '.join(missing)}",
            ">",
            "> This artifact was rendered from a subset of the pipeline, so it is **not** a "
            "whole "
            "run and must not be committed as one. Numbers below cover only the stages "
            "listed in "
            "the provenance table; anything a skipped stage would have produced is absent "
            "rather "
            "than zero.",
            "",
        ]
    parts += [_provenance_table(provenance, golden), ""]
    parts += [
        "## Per-bucket A/B — the deterministic retrieval metrics",
        "",
        "No judge, no spend: every figure below is computed from `Retrieval`'s own return "
        "value "
        "against the golden set's chunk ids, so a reviewer can re-derive it. Recall columns "
        "exclude whole `recall_trivial` rows (reported separately) and count only sections a "
        f"`k={provenance.k}` retrieval could miss.",
        "",
        "**Read `chunk recall` and `section recall` together, and neither as a quality score "
        "on "
        "its own.** `chunk recall` asks whether the retriever returned the *specific chunks* a "
        "reference was authored from, and those references were authored from a handful of "
        "chunks "
        "inside sections that are often very large — S1 names 6 of TSLA Item 1A's **129**. At "
        f"`k={provenance.k}` that is close to a lottery even for a retrieval doing everything "
        "right: this harness's first live run returned Item 1A chunks 48-70 against targets "
        "0, 1, "
        "6, 34, 94 and 117 — chunk recall 0.000, section recall 1.000, for a result an analyst "
        "would call correct. So `chunk recall` is reported because it is exact and free, "
        "`section recall` because it is what the multi-hop and cross-filer rows are about, and "
        "the judged `context precision` / `context recall` below because they compare *text* "
        "against the reference rather than chunk identity. That is why ADR-0005's "
        "falsification "
        "clause rests on those two and not on this column.",
        "",
        free_metric_table(cells, arms),
        "",
    ]
    parts += [
        "## RAGAs — all four metrics, per bucket",
        "",
        ragas_table(cells, arms),
        "",
    ]
    if ablations:
        parts += [
            "## Ablations — the planner off (ADR-0004 §7, ADR-0005 §2)",
            "",
            "Translation on, `max_sub_queries=0`: the deterministic ticker form is still "
            "added and "
            "no model is asked anything, which is the channel ADR-0005 §2 pre-registered for "
            "refuting its own revised hypothesis. Retrieval metrics only — these cells exist "
            "to "
            "attribute a retrieval result, and faithfulness over an answer is not evidence "
            "about "
            "which candidate list found a chunk.",
            "",
            free_metric_table(cells, ablations),
            "",
        ]
    for heading, body in sections:
        parts += [heading, "", body, ""]
    return "\n".join(parts).rstrip() + "\n"


def _provenance_table(provenance: Provenance, golden: GoldenSet) -> str:
    cache_lines = ", ".join(
        f"{kind} {stats.hits} replayed / {stats.misses} paid"
        + (f" / {stats.malformed} unreadable" if stats.malformed else "")
        for kind, stats in sorted(provenance.cache.items())
    )
    rows: list[tuple[str, str]] = [
        ("generated", provenance.generated_at),
        ("stages run", ", ".join(provenance.stages)),
        ("judge model", f"`{provenance.judge_model}` (ragas {provenance.ragas_version})"),
        ("answering model", f"`{provenance.chat_model}`"),
        ("planner model", f"`{provenance.planner_model}`"),
        ("embedding model", f"`{provenance.embedding_model}`"),
        ("k", str(provenance.k)),
        ("golden set", f"{provenance.golden_set_rows} rows, verified against EDGAR"),
        ("collection", provenance.collection_ingest_run),
        ("collection fingerprint", f"`{provenance.collection_fingerprint[:16]}…`"),
        ("cache", cache_lines or "not used"),
    ]
    del golden
    return "\n".join(
        ["| | |", "|---|---|"] + [f"| {label} | {value} |" for label, value in rows]
    )


def hypothesis_section(entries: Sequence[Mapping[str, Any]]) -> str:
    """Each pre-registered prediction, then its measurement, then confirmed or refuted.

    Prediction **first**, in its own column, so the artifact cannot be read as having fitted
    the prediction to the result — which is the whole reason ADR-0005 pre-registers anything.
    A refuted prediction is a result: ADR-0004 §6 is the precedent, where a pre-registered
    hypothesis failed and the failure improved the ADR.
    """
    lines = [
        "| # | prediction (pre-registered) | measurement | verdict |",
        "|---|---|---|---|",
    ]
    for index, entry in enumerate(entries, start=1):
        lines.append(
            f"| {index} | {entry['prediction']} | {entry['measurement']} "
            f"| **{entry['verdict']}** |"
        )
    return "\n".join(lines)


def decisions_section(clauses: Sequence[Any], trigger: Any, *, default_arm_label: str) -> str:
    """ADR-0005's two pre-registered triggers, and what this run did to them.

    Both are printed whether they fired or not. A trigger reported only when it fires is a
    trigger a reader cannot tell was evaluated — and ADR-0005 §4's fires on an *absence* of
    gain, which is exactly the shape that goes unnoticed if it is not printed.
    """
    lines = [
        "### Falsification clause (ADR-0005) — translation, per bucket",
        "",
        "Fires only when translation is worse on **both** context precision **and** context "
        "recall within a bucket, each by more than its own per-question spread. Directional "
        "and "
        "two-sided by design: with ~7 questions per bucket a tight numeric margin would be "
        "false "
        "precision, and dropping a pre-registered default on half the evidence would be worse "
        "than keeping it.",
        "",
        "| bucket | context precision | context recall | clause |",
        "|---|---|---|---|",
    ]
    for clause in clauses:
        state = "**FIRES**" if clause.fires else "does not fire"
        lines.append(
            f"| {clause.bucket.value} | {clause.precision.value} | {clause.recall.value} "
            f"| {state} |"
        )
    fired = [c.bucket.value for c in clauses if c.fires]
    lines += [
        "",
        (
            f"**Outcome: the clause fires on {', '.join(fired)}, so the shipping default drops "
            f"to `hybrid-only` and the contradiction is the finding.**"
            if fired
            else f"**Outcome: the clause does not fire on any bucket, so the pre-committed "
            f"default stands: {default_arm_label}.**"
        ),
        "",
        "### Re-examination trigger (ADR-0005 §4) — the strategy axis",
        "",
        "Fires on an **absence of gain**, not on a loss: if `hybrid − vector` at equal "
        "translation is within per-question spread on *every* bucket, the dominance argument "
        "is "
        "re-argued rather than defended and `vector + translation` becomes a live candidate "
        "for "
        "the default. Registered before any number existed, because a default kept because its "
        "marginal component was never separately measured is p-hacking in the other direction.",
        "",
        "| bucket | hybrid − vector, both +translation |",
        "|---|---|",
    ]
    for bucket, verdict in trigger.per_bucket.items():
        lines.append(f"| {bucket.value} | {verdict.value} |")
    lines += [
        "",
        (
            "**Outcome: the trigger FIRES — hybrid adds nothing beyond spread on any settled "
            "bucket, so ADR-0005's dominance argument is re-argued rather than defended.**"
            if trigger.fires
            else "**Outcome: the trigger does not fire.** Hybrid's contribution exceeds "
            "per-question spread on at least one bucket, so the dominance argument stands as "
            "argued."
        ),
    ]
    if trigger.undetermined:
        names = ", ".join(bucket.value for bucket in trigger.undetermined)
        lines += [
            "",
            f"Undetermined on: {names}. Those buckets produced no comparable number, which "
            f"weakens the conclusion in whichever direction it went — an absence is not "
            "evidence "
            f"for either arm.",
        ]
    return "\n".join(lines)


def latency_section(cost: Any, spends: Sequence[Any]) -> str:
    """ADR-0005's ≤1.5s p50 budget, and the token counts, both from the log."""
    verdict = "within budget" if cost.within_budget else "**over budget**"
    lines = [
        "Measured from the persisted event log (`FINBRIEF_LOG_FILE`), not from a stopwatch: a "
        "stopwatch around `retrieve()` cannot split the planner's chat round from the "
        "retrieval "
        "rounds, and ADR-0004's amendment makes that split the interesting half of the budget.",
        "",
        "| | ms | samples |",
        "|---|---:|---:|",
        f"| planner's chat round, p50 | {cost.planner_p50_ms:.0f} | {cost.planner_samples} |",
        f"| retrieval p50, translation on | {cost.retrieval_translated_p50_ms:.0f} "
        f"| {cost.translated_samples} |",
        f"| retrieval p50, translation off | {cost.retrieval_untranslated_p50_ms:.0f} "
        f"| {cost.untranslated_samples} |",
        f"| retrieval rounds translation adds, p50 | {cost.retrieval_delta_p50_ms:.0f} | — |",
        f"| **total p50 added by translation** | **{cost.added_p50_ms:.0f}** | — |",
        f"| ADR-0005's budget | {cost.budget_ms:.0f} | — |",
        "",
        f"**Verdict: {verdict}.**",
        "",
        "**The planner's figure comes from the resolve pass, and that is a reconstruction "
        "rather "
        "than one measurement.** ADR-0004 §9's replay means the scored `+translation` arms "
        "serve "
        "the planner's reply from a stub, so their own `query_translation` lines record ~1 "
        "ms and "
        "no token counts — the harness only reads lines that reported spend, since a line "
        "with no "
        "`input_tokens` called no model. Adding that median to the retrieval delta is the "
        "honest "
        "reconstruction of what the shipped path pays; it is not a single timing of a live "
        "turn.",
        "",
        "| metered event | input tokens | output tokens | lines | unmetered lines |",
        "|---|---:|---:|---:|---:|",
    ]
    for spend in spends:
        lines.append(
            f"| `{spend.event}` | {spend.input_tokens} ({spend.input_calls} calls) "
            f"| {spend.output_tokens} ({spend.output_calls} calls) | {spend.lines} "
            f"| {spend.unmetered_lines} |"
        )
    lines += [
        "",
        "An unmetered line is a call whose cost is **unknown**, not free "
        "(`observability/tokens.py`): each count carries its own denominator because a "
        "provider "
        "that reports half a pair must not put a fabricated zero on the line. The gate "
        "classifier's tokens are unmeasured by decision (ADR-0011), and the embeddings API "
        "returns no usage this code path can see.",
    ]
    return "\n".join(lines)


def headline_section(
    cells: Sequence[Cell],
    *,
    default_arm: Arm,
    judge_calls: int,
    cache_replayed: int,
) -> str:
    """The figures T11's README quotes, in one place, each with its denominator.

    A deliberate short list rather than a summary of everything: the README's job is to state
    what was measured and point at the artifact, and a figure retyped into prose is a figure
    that will disagree with its source (`config.ALPHAVANTAGE_FREE_TIER_CALLS_PER_DAY`'s
    docstring makes the same point about a number written in four places). Everything here is
    derived from the cells this run scored, so re-running rewrites it.
    """
    rows = [row for row in cells if row.arm == default_arm.name]
    faith = _summarise_judged(rows, "faithfulness")
    precision = Summary.of(row.judged.get("context_precision") for row in rows)
    recall = Summary.of(row.judged.get("context_recall") for row in rows)
    section_recall = summarise(
        [row.score for row in rows], "section_recall", exclude_trivial=True
    )
    lines = [
        f"Measured on the shipping default ({default_arm.label}), over "
        f"{len(rows)} golden-set rows. **Quote these from here, not from prose.**",
        "",
        "| figure | value | denominator |",
        "|---|---|---|",
        f"| RAGAs faithfulness | {cell(faith)} | rows scored on the default arm |",
        f"| RAGAs context precision | {cell(precision)} | as above |",
        f"| RAGAs context recall | {cell(recall)} | as above |",
        f"| section recall (free, deterministic) | {cell(section_recall)} "
        f"| non-trivial target sections |",
        f"| judge calls this run paid for | {judge_calls} | at k=5, six arms |",
        f"| cells replayed from cache | {cache_replayed} | see the provenance table |",
        "",
        "**Response relevancy is deliberately absent from this list.** It is reported in the "
        "RAGAs "
        "table with its spread, and it is excluded from every pre-registered decision — "
        "quoting it "
        "as a headline number would be quoting a figure that moves between runs.",
    ]
    return "\n".join(lines)


#: The four measurements earlier tickets deferred to T10, and what each needs.
#:
#: Rendered into the artifact **whether or not they ran**, because an unscored criterion reads
#: as a passed one — the failure #9's comment on the AC-1 pairing names explicitly ("what must
#: not happen is the third option *without* the sentence"). Three of the four need live agent
#: turns, which is a different and nondeterministic instrument from the chain these tables
#: measure.
DEFERRALS: tuple[tuple[str, str, str], ...] = (
    (
        "agent-vs-original query divergence rate",
        "T4 (ADR-0003 amendment §2)",
        "`agent_query.verbatim` over live agent turns",
    ),
    (
        "square-bracket rule adherence rate",
        "T5 (ADR-0006 T7 amendment §4)",
        "`citation_markers` over live agent turns",
    ),
    (
        "layer 4's residue — advice phrased so no rule matches",
        "T7 (ADR-0006 T7 amendment §4)",
        "advice probes through the live agent and `security.advice.validate_answer`",
    ),
    (
        "faithfulness on markers that resolve but sit on unsupported claims",
        "T3/T5",
        "per-sentence NLI against the *cited* chunk, not the whole context set",
    ),
)


def deferrals_section(measured: Mapping[str, str] | None = None) -> str:
    """The deferred measurements, each either reported or explicitly named as not run.

    `measured` maps a deferral's name to its result. Anything absent renders as **not measured
    by this run**, which is the honest form of "we did not get to it" — a row in a table
    rather than an omission a reader has to notice.
    """
    measured = measured or {}
    lines = [
        "Four measurements were deferred to this ticket by earlier ones. They are listed here "
        "whether or not they ran, because an unscored criterion reads as a passed one. Three "
        "of "
        "the four need **live agent turns**, which is a different and nondeterministic "
        "instrument "
        "from the chain every table above measures — so they belong beside the RAGAs tables "
        "and "
        "never inside them.",
        "",
        "| deferred measurement | from | instrument | result |",
        "|---|---|---|---|",
    ]
    for name, source, instrument in DEFERRALS:
        result = measured.get(name, "**not measured by this run**")
        lines.append(f"| {name} | {source} | {instrument} | {result} |")
    if not measured:
        lines += [
            "",
            "None of the four ran. The events they read are emitted and their readers exist "
            "(`observability/events.py`, `evaluation/latency.py`); what is missing is a "
            "live-run "
            "sample large enough to publish a rate from. The only sample that exists is the "
            "one "
            "ADR-0003's T4 amendment already records — 0 verbatim of 2 searches across two "
            "conversations — and that amendment says itself that it is too small to publish.",
        ]
    return "\n".join(lines)
